import { describe, expect, it } from "vitest";
import { classifyFile } from "../src/classify.js";
import { globToRegExp } from "../src/glob.js";
import { scopeForPath } from "../src/infer-scope.js";
import { extractSymbol } from "../src/symbols.js";
import type { DiffFile } from "../src/types.js";

function file(path: string, overrides: Partial<DiffFile> = {}): DiffFile {
  return { path, oldPath: path, status: "modified", binary: false, additions: 0, deletions: 0, hunks: [], ...overrides };
}

function addedFile(path: string, lines: string[]): DiffFile {
  return file(path, {
    status: "added",
    additions: lines.length,
    hunks: [
      {
        header: `@@ -0,0 +1,${lines.length} @@`,
        oldStart: 0,
        oldLines: 0,
        newStart: 1,
        newLines: lines.length,
        section: "",
        lines: lines.map((content) => ({ kind: "add" as const, content })),
      },
    ],
  });
}

describe("globToRegExp", () => {
  it.each([
    ["*.md", "README.md", true],
    ["*.md", "docs/deep/guide.md", true],
    ["docs/**", "docs/a/b.md", true],
    ["docs/**", "src/docs/a.md", false],
    ["**/dist/**", "dist/index.js", true],
    ["**/dist/**", "packages/core/dist/index.js", true],
    ["apps/web/**", "apps/web/src/a.ts", true],
    ["apps/web/**", "apps/website/a.ts", false],
    ["*.{png,jpg}", "a/b.jpg", true],
    ["src/?.ts", "src/a.ts", true],
    ["src/?.ts", "src/ab.ts", false],
    ["a.b", "axb", false],
  ])("%s matches %s: %s", (glob, path, expected) => {
    expect(globToRegExp(glob).test(path)).toBe(expected);
  });
});

describe("classifyFile", () => {
  it.each([
    ["pnpm-lock.yaml", "lockfile"],
    ["packages/x/yarn.lock", "lockfile"],
    ["src/__snapshots__/a.test.ts.snap", "snapshot"],
    ["public/app.min.js", "minified"],
    ["packages/core/dist/index.js", "generated"],
    ["src/api.generated.ts", "generated"],
    [".github/workflows/ci.yml", "ci"],
    [".github/dependabot.yml", "config"],
    ["src/a.test.ts", "test"],
    ["pkg/server/handler_test.go", "test"],
    ["tests/test_models.py", "test"],
    ["fixtures/docs-only/input.diff", "test"],
    ["README.md", "docs"],
    ["docs/setup.txt", "docs"],
    ["package.json", "manifest"],
    ["tsconfig.json", "config"],
    ["eslint.config.mjs", "config"],
    ["assets/logo.svg", "asset"],
    ["src/index.ts", "source"],
    ["src/build/compile.ts", "source"],
  ])("%s is %s", (path, category) => {
    expect(classifyFile(file(path)).category).toBe(category);
  });

  it("marks binary files as noise regardless of path", () => {
    expect(classifyFile(file("src/data.bin", { binary: true }))).toMatchObject({ category: "binary", noiseReason: "binary file" });
  });

  it("detects generated-code markers at the top of the file", () => {
    expect(classifyFile(addedFile("src/schema.ts", ["// Code generated by protoc. DO NOT EDIT.", "export {}"])).category).toBe("generated");
    expect(classifyFile(addedFile("src/a.ts", ["export {}", "", "", "", "", "// do not edit below"])).category).toBe("source");
  });

  it("detects minified content by line length", () => {
    expect(classifyFile(addedFile("src/vendor.js", ["x".repeat(2000)])).category).toBe("minified");
  });

  it("applies user ignore globs first", () => {
    expect(classifyFile(file("src/legacy/a.ts"), { ignore: ["src/legacy/**"] }).category).toBe("ignored");
  });
});

describe("scopeForPath", () => {
  it.each([
    ["apps/web/src/App.tsx", "web"],
    ["packages/@acme-ui/src/a.ts", "acme-ui"],
    ["packages/core/README.md", "core"],
    ["src/auth/login.ts", "auth"],
    ["src/index.ts", undefined],
    ["lib/parser/index.js", "parser"],
    ["api/handlers/users.go", "api"],
    ["internal/store/db.go", "store"],
    ["README.md", undefined],
    [".github/workflows/ci.yml", undefined],
    ["docs/guide.md", undefined],
    ["packages/x", undefined],
  ])("%s -> %s", (path, scope) => {
    expect(scopeForPath(path)).toBe(scope);
  });

  it("prefers configured mappings", () => {
    expect(scopeForPath("apps/web/src/a.ts", { scopeFromPaths: { "apps/web/**": "frontend" } })).toBe("frontend");
  });
});

describe("extractSymbol", () => {
  it.each([
    ["export function login() {", { name: "login", exported: true }],
    ["export default async function handler(req) {", { name: "handler", exported: true }],
    ["export const API_URL = 'x';", { name: "API_URL", exported: true }],
    ["export interface User {", { name: "User", exported: true }],
    ["function helper() {", { name: "helper", exported: false }],
    ["class Cache {", { name: "Cache", exported: false }],
    ["def parse(text):", { name: "parse", exported: true }],
    ["    def _inner(self):", { name: "_inner", exported: false }],
    ["class Model(Base):", { name: "Model", exported: true }],
    ["func (s *Server) Start() error {", { name: "Start", exported: true }],
    ["func helper() {", { name: "helper", exported: false }],
    ["pub fn run() {", { name: "run", exported: true }],
    ["fn private() {", { name: "private", exported: false }],
  ])("%s", (line, expected) => {
    expect(extractSymbol(line)).toEqual(expected);
  });

  it("ignores ordinary statements", () => {
    expect(extractSymbol("const x = 1;")).toBeUndefined();
    expect(extractSymbol("return classify(file);")).toBeUndefined();
  });
});
