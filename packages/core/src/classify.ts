/** A file is likely minified when lines are very long on average. */
const MINIFIED_AVG_LINE = 300;
const MINIFIED_MAX_LINE = 1000;

export interface ClassifyOptions {
  /** Extra globs to treat as noise (from the user's config). */
  ignore?: readonly string[];
}

export function classifyFile(file: DiffFile, options: ClassifyOptions = {}): ClassifiedFile {
  const [category, noiseReason] = categorize(file, options);
  const classified: ClassifiedFile = { ...file, category };
  if (noiseReason) classified.noiseReason = noiseReason;
  return classified;
}

export function classifyFiles(files: readonly DiffFile[], options: ClassifyOptions = {}): ClassifiedFile[] {
  return files.map((file) => classifyFile(file, options));
}

export interface FilterResult {
  /** Files whose content is meaningful for the message. */
  kept: ClassifiedFile[];
  /** Noise: lockfiles, generated, minified, snapshots, binary, user-ignored. */
  dropped: ClassifiedFile[];
}

export function filterNoise(files: readonly ClassifiedFile[]): FilterResult {
  const kept: ClassifiedFile[] = [];
  const dropped: ClassifiedFile[] = [];
  for (const file of files) (isNoise(file) ? dropped : kept).push(file);
  return { kept, dropped };
}

export function isNoise(file: ClassifiedFile): boolean {
  return NOISE_CATEGORIES.has(file.category);
}

function categorize(file: DiffFile, options: ClassifyOptions): [FileCategory, string?] {
  const path = file.path;
  const ci = { nocase: true };

  if (options.ignore?.length && matchesAny(path, options.ignore)) return ["ignored", "matches an ignore pattern"];
  if (file.binary) return ["binary", "binary file"];
  if (matchesAny(path, LOCKFILES, ci)) return ["lockfile", "lockfile"];
  if (matchesAny(path, SNAPSHOTS, ci)) return ["snapshot", "test snapshot"];
  if (matchesAny(path, MINIFIED, ci) || looksMinified(file)) return ["minified", "minified or source map"];
  if (matchesAny(path, GENERATED, ci)) return ["generated", "build output or generated path"];
  if (hasGeneratedMarker(file)) return ["generated", "file is marked as generated"];

  if (matchesAny(path, CI, ci)) return ["ci"];
  if (matchesAny(path, TESTS, ci)) return ["test"];
  if (matchesAny(path, DOCS, ci)) return ["docs"];
  if (matchesAny(path, MANIFESTS, ci)) return ["manifest"];
  if (matchesAny(path, CONFIG, ci)) return ["config"];
  if (matchesAny(path, ASSETS, ci)) return ["asset"];
  return ["source"];
}

function looksMinified(file: DiffFile): boolean {
  let total = 0;
  let count = 0;
  let longest = 0;
  for (const hunk of file.hunks) {
    for (const line of hunk.lines) {
      if (line.kind !== "add") continue;
      total += line.content.length;
      count++;
      longest = Math.max(longest, line.content.length);
    }
  }
  return count > 0 && total / count > MINIFIED_AVG_LINE && longest > MINIFIED_MAX_LINE;
}

/** Look for a generated-code marker near the top of the new file. */
function hasGeneratedMarker(file: DiffFile): boolean {
  const first = file.hunks[0];
  if (!first || first.newStart > 1) return false;
  let seen = 0;
  for (const line of first.lines) {
    if (line.kind === "del") continue;
    if (GENERATED_MARKER.test(line.content)) return true;
    if (++seen >= 5) break;
  }
  return false;
}
